    @Test
    @DisplayName("GET /dashboard renders Title|Type|Score table ordered by final_score DESC, id ASC, limited to 20")
    void defaultDashboardRendersOrderedTopTwentyTable() {
        seedFixture();

        ResponseEntity<String> response = getDashboard("/dashboard");

        assertThat(response.getStatusCode()).isEqualTo(HttpStatus.OK);
        assertThat(response.getHeaders().getContentType())
                .matches(ct -> ct != null && ct.includes(MediaType.TEXT_HTML));

        String body = response.getBody();
        assertThat(body).isNotNull();

        // REQ 10.2: exactly the three columns Title | Type | Score
        assertThat(body)
                .contains("<th scope=\"col\">Title</th>")
                .contains("<th scope=\"col\">Type</th>")
                .contains("<th scope=\"col\">Score</th>");

        // REQ 10.3: top 20 rows present (Title-01..Title-20); rows 21-22 absent.
        for (int i = 1; i <= 20; i++) {
            String title = String.format("Title-%02d", i);
            assertThat(body).as("row %d should be rendered", i).contains(title);
        }
        assertThat(body)
                .doesNotContain("Title-21")
                .doesNotContain("Title-22");

        // REQ 10.3: order is final_score DESC; rows 01 and 02 share final_score
        // = 100.0 so the id-ASC tie-break must place Title-01 above Title-02.
        // After the tie, the remaining rows must appear in numeric order
        // because their final_scores are strictly decreasing.
        int previous = -1;
        for (int i = 1; i <= 20; i++) {
            String title = String.format("Title-%02d", i);
            int idx = body.indexOf(title);
            assertThat(idx).as("Title-%02d must appear in the body", i).isPositive();
            assertThat(idx)
                    .as("Title-%02d must come after Title-%02d", i, i - 1)
                    .isGreaterThan(previous);
            previous = idx;
        }

        // No "ignored" notice on a clean default request (REQ 10.5/10.7 negative case).
        assertThat(body).doesNotContain("data-testid=\"ignored-notice\"");
        assertThat(body).doesNotContain("data-testid=\"empty-message\"");
    }

