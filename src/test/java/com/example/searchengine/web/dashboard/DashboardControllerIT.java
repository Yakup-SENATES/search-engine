    private ResponseEntity<String> getDashboard(String path) {
        return restTemplate.getForEntity("http://localhost:" + port + path, String.class);
    }

    /**
     * Flattens an HTML fragment by stripping every tag and collapsing all
     * whitespace runs to a single space. This is enough for assertions on
     * visible textual content (e.g. {@code "Showing 20 results sorted by score"})
     * that would otherwise be split across nested {@code <span>} elements and
     * Thymeleaf-preserved newlines in the source template.
     */
    private static String flattenText(String html) {
        String noTags = html.replaceAll("<[^>]+>", " ");
        return noTags.replaceAll("\\s+", " ").trim();
    }

    /**
     * Seeds 22 rows with predictable, deterministic scores and stable UUIDs.
     *
     * <p>Layout:
     * <ul>
     *   <li>Rows 1..15: type {@link ContentType#VIDEO}</li>
     *   <li>Rows 16..22: type {@link ContentType#TEXT}</li>
     *   <li>Rows 1 and 2 share {@code final_score = 100.0} so the id-ASC
     *       tie-break can be observed (row 1's UUID is lexicographically
     *       smaller than row 2's UUID — see {@link #uuidWithSuffix(int)}).</li>
     *   <li>Rows 3..22 have strictly-decreasing {@code final_score}
     *       (99.0, 98.0, ..., 80.0).</li>
     *   <li>{@code popularity_score} is set to {@code i} so the ordering by
     *       popularity is the reverse of the ordering by final_score.</li>
     * </ul>
     */
    private void seedFixture() {
        Instant publishedAt = Instant.parse("2024-08-01T12:00:00Z");

        for (int i = 1; i <= 22; i++) {
            // final_score: rows 1 and 2 tie at 100.0; the rest decrease by 1.
            double finalScore = (i <= 2) ? 100.0 : (102.0 - i);
            // popularity_score: monotonically increases with i so the
            // popularity ordering is the reverse of the score ordering.
            double popularityScore = (double) i;

            Content content = new Content(
                    uuidWithSuffix(i),
                    "test-provider",
                    "ext-" + i,
                    String.format("Title-%02d", i),
                    "description for row " + i,
                    i <= 15 ? ContentType.VIDEO : ContentType.TEXT,
                    100L,
                    10L,
                    5,
                    2L,
                    null,
                    List.of(),
                    publishedAt,
                    finalScore,
                    popularityScore,
                    0.0,
                    null,  // createdAt — managed by the database
                    null   // updatedAt — managed by the database
            );
            contentRepository.upsert(content);
        }
    }

    /**
     * Seeds {@code n} rows with deterministic, strictly-decreasing
     * {@code final_score} values so the dashboard ordering for the top 20
     * is fully predictable. Used by the REQ 10.1 performance scenario.
     *
     * <p>Rows alternate {@code VIDEO} and {@code TEXT} types so the
     * dashboard's mixed-type rendering path is exercised. UUIDs follow the
     * same {@link #uuidWithSuffix(int)} convention.</p>
     */
    private void seedLargeFixture(int n) {
        Instant publishedAt = Instant.parse("2024-08-01T12:00:00Z");

        for (int i = 1; i <= n; i++) {
            Content content = new Content(
                    uuidWithSuffix(i),
                    "test-provider",
                    "big-" + i,
                    String.format("BIG-%04d", i),
                    "row " + i,
                    (i % 2 == 0) ? ContentType.VIDEO : ContentType.TEXT,
                    100L,
                    10L,
                    5,
                    2L,
                    null,
                    List.of(),
                    publishedAt,
                    // Strictly-decreasing finalScore so row 1 ranks highest
                    // and row n ranks last.
                    (double) (n - i + 1),
                    (double) i,
                    0.0,
                    null,
                    null
            );
            contentRepository.upsert(content);
        }
    }

    /**
     * Returns a deterministic {@link UUID} of the form
     * {@code 00000000-0000-0000-0000-XXXXXXXXXXXX} where the trailing 12 hex
     * digits encode {@code n}. This guarantees a stable lexicographic /
     * numeric ordering by {@code n}, which is what the {@code id ASC}
     * tie-break observed by the dashboard relies on.
     */
    private static UUID uuidWithSuffix(int n) {
        return UUID.fromString(String.format("00000000-0000-0000-0000-%012d", n));
    }
