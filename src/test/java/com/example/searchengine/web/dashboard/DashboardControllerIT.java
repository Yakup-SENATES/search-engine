    @Test
    @DisplayName("GET /dashboard?sort=popularity orders rows by popularity_score DESC")
    void sortPopularityChangesOrdering() {
        seedFixture();

        ResponseEntity<String> response = getDashboard("/dashboard?sort=popularity");

        assertThat(response.getStatusCode()).isEqualTo(HttpStatus.OK);
        String body = response.getBody();
        assertThat(body).isNotNull();

        // popularity_score is set so that higher row numbers have higher
        // popularity. The top 20 by popularity DESC are rows 22 down to 3.
        // Rows 1 and 2 (popularity 1 and 2) must be excluded.
        assertThat(body)
                .doesNotContain("Title-01")
                .doesNotContain("Title-02");
        for (int i = 3; i <= 22; i++) {
            assertThat(body).contains(String.format("Title-%02d", i));
        }

        // Ordering: Title-22 first, Title-21 second, ..., Title-03 last.
        int previous = -1;
        for (int i = 22; i >= 3; i--) {
            String title = String.format("Title-%02d", i);
            int idx = body.indexOf(title);
            assertThat(idx).as("Title-%02d must appear", i).isPositive();
            assertThat(idx)
                    .as("Title-%02d (popularity=%d) must come after the previous higher-popularity title", i, i)
                    .isGreaterThan(previous);
            previous = idx;
        }

        // No ignored-notice for a valid sort value.
        assertThat(body).doesNotContain("data-testid=\"ignored-notice\"");
    }

